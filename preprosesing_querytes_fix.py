"""##  Mesin Pencari Berita"""

def perform_search(query_input, top_n=5):
    # preprocessing
    query = query_input.lower()
    remove_punctuation_map = dict((ord(char), None) for char in string.punctuation)
    query = query.translate(remove_punctuation_map)
    query = stopword.remove(query)
    query = [stemmer.stem(t) for t in query.split()]
    query_str = ' '.join(query)

    # TF-IDF
    vectorizer = TfidfVectorizer(use_idf=True)
    corpus = [query_str] + processed_paper
    paper_tfidf = vectorizer.fit_transform(corpus)
    query_vector = paper_tfidf[0]
    similarity_scores = cosine_similarity(paper_tfidf, query_vector)

    # hasil
    results = []
    for doc_idx in range(1, len(similarity_scores)):
        score = similarity_scores[doc_idx][0]
        if score > 0:
            i = doc_idx - 1
            results.append({
                'Document_ID': i,
                'Score': round(score, 4),
                'Judul': paper[i][1],
                'Waktu': paper[i][2],
                'Konten': paper[i][3]
            })

    results = sorted(results, key=lambda x: x['Score'], reverse=True)
    return results[:top_n]

# Interface UI

output = widgets.Output()

search_box = widgets.Text(
    placeholder='Ketik kata kunci pencarian...',
    description='Cari:',
    layout=widgets.Layout(width='500px'),
    style={'description_width': 'initial'}
)

search_button = widgets.Button(
    description='Cari',
    button_style='primary',
    layout=widgets.Layout(width='100px')
)

def on_search(b=None):
    with output:
        clear_output(wait=True)
        query = search_box.value.strip().lower()

        if not query:
            print("Masukkan kata kunci pencarian terlebih dahulu.")
            return

        print(f"Mencari berita yang relevan dengan: '{query}'")
        results = perform_search(query, top_n=50)

        if results:
            print(f"\nMenunjukkan {len(results)} hasil teratas:\n")
            display(pd.DataFrame(results))
        else:
            print("Tidak ada hasil yang ditemukan.")

search_button.on_click(on_search)
search_box.on_submit(on_search)

display(widgets.VBox([
    widgets.HBox([search_box, search_button]),
    output
]))