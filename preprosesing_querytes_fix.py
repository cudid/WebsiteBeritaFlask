# Load file kompas
paper_x = pd.read_excel('/content/sample_data/hasil_scraping_kompas.xlsx')

# Kolom: 0=URL, 1=Judul, 2=Waktu, 3=Content
paper = paper_x.values.tolist()

print(f"Total data berita: {len(paper)}")

# Preprocessing korpus berita

factory = StopWordRemoverFactory()
stopword = factory.create_stop_word_remover()
stemmer = StemmerFactory().create_stemmer()
processed_paper = []
words = []

for x in tqdm(paper, desc='Processing Berita', unit='berita'):
    # x[1] adalah Judul, x[3] adalah Content
    text_gabungan = str(x[1]) + " " + str(x[3])

    text = text_gabungan.lower()
    remove_punctuation_map = dict((ord(char), None) for char in string.punctuation)
    text = text.translate(remove_punctuation_map)
    text = stopword.remove(text)

    tokens = text.split()
    stemmed_tokens = [stemmer.stem(t) for t in tokens]

    processed_paper.append(' '.join(stemmed_tokens))
    words += list(set(stemmed_tokens))

print("Preprocessing selesai.")

print("Menyimpan data ke corpus/processed_kompas2_uts.xlsx...")
df = pd.DataFrame(processed_paper)
df.to_excel('/content/sample_data/processed_kompas2_uts.xlsx', header=False, index=False)
print("Sukses.")

print("Menyimpan data ke corpus/kompas_words2_uts.xlsx...")
df = pd.DataFrame(words)
